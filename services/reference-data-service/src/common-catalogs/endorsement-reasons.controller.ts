import { Body, Controller, Get, Param, Patch, Post } from '@nestjs/common';
import { CurrentUser, JwtPayload, Roles } from '@ars-platform/shared-common';
import { EndorsementReasonsService } from './endorsement-reasons.service';
import { CreateEndorsementReasonDto } from './dto/create-endorsement-reason.dto';
import { UpdateEndorsementReasonDto } from './dto/update-endorsement-reason.dto';
import { SetCatalogStateDto } from './dto/set-catalog-state.dto';

@Controller('endorsement-reasons')
export class EndorsementReasonsController {
  constructor(private readonly service: EndorsementReasonsService) {}

  @Get()
  findAll() {
    return this.service.findAll();
  }

  @Get(':id')
  findOne(@Param('id') id: string) {
    return this.service.findOne(id);
  }

  @Roles('ADMIN')
  @Post()
  create(@Body() dto: CreateEndorsementReasonDto, @CurrentUser() actor: JwtPayload) {
    return this.service.create(dto, actor.code);
  }

  @Roles('ADMIN')
  @Patch(':id')
  update(@Param('id') id: string, @Body() dto: UpdateEndorsementReasonDto, @CurrentUser() actor: JwtPayload) {
    return this.service.update(id, dto, actor.code);
  }

  @Roles('ADMIN')
  @Patch(':id/state')
  setState(@Param('id') id: string, @Body() dto: SetCatalogStateDto, @CurrentUser() actor: JwtPayload) {
    return this.service.setState(id, dto.codState, actor.code);
  }
}
